const POOL_SIZE = 8
const SHUFFLE_BEFORE_ADD = 8

function shuffle(arr) {
  const a = arr.slice()
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

/** 从词包抽一页候选（排除已选） */
function nextPool(pack, selected, size) {
  const selectedSet = {}
  ;(selected || []).forEach((t) => {
    selectedSet[t] = true
  })
  const rest = (pack || []).filter((t) => !selectedSet[t])
  if (!rest.length) return []
  return shuffle(rest).slice(0, size || POOL_SIZE)
}

